/**
 * DeFi protocol catalog — the ONE copy both runtimes read.
 *
 * `src/lib/defi-registry.ts` (Vite) and `_shared/binance-web3-defi.ts` (Deno) used
 * to carry this table independently: 25 entries each, ~2,600 lines, and they had
 * already drifted (one auditor name cased differently). Neither runtime can import
 * the other's module, but a data table has no runtime dependency — so it lives here,
 * beside the edge function that owns the Binance Web3 protocol vocabulary, and the
 * SPA imports it across the tree. Vite resolves it; Deno needs the explicit `.ts`.
 *
 * Two fields are intentionally loose: `category` and `supportedChainIds` are plain
 * `string`/`string[]` here and each runtime narrows to its own union, because the
 * two unions were never identical (the SPA also models RWA/VAULT investments).
 *
 * The edge's 10 shorter agent-facing descriptions live in an override map in
 * `binance-web3-defi.ts` — user-facing copy and agent copy are deliberately
 * different strings, and unifying the TABLE must not unify the PROSE.
 */
